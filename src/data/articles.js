export function getArticleBySlug(slug) {
  return articles.find((a) => a.slug === slug) || null;
}

export function getArticleCategories() {
  return [...new Set(articles.map((a) => a.category))];
}

export function buildArticleSchema(article) {
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'Article',
        '@id': `${BASE_URL}${article.canonicalPath}`,
        headline: article.title,
        description: article.metaDescription,
        url: `${BASE_URL}${article.canonicalPath}`,
        datePublished: article.publishedAt,
        dateModified: article.updatedAt || article.publishedAt,
        inLanguage: 'he',
        publisher: {
          '@type': 'LegalService',
          name: 'ברזילי, עזורי ושות׳ עורכי דין',
          url: BASE_URL,
        },
      },
      ...(article.faq
        ? [
            {
              '@type': 'FAQPage',
              mainEntity: article.faq.map(({ q, a }) => ({
                '@type': 'Question',
                name: q,
                acceptedAnswer: { '@type': 'Answer', text: a },
              })),
            },
          ]
        : []),
      {
        '@type': 'BreadcrumbList',
        itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'דף הבית', item: BASE_URL },
          { '@type': 'ListItem', position: 2, name: 'מאמרים', item: `${BASE_URL}/articles` },
          { '@type': 'ListItem', position: 3, name: article.title, item: `${BASE_URL}${article.canonicalPath}` },
        ],
      },
    ],
  };
}
